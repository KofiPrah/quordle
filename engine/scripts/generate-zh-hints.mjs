import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const modulePath = fileURLToPath(import.meta.url);
const defaultEngineRoot = path.resolve(path.dirname(modulePath), '..');

function pinyinKey(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/u:/gu, 'v')
    .replace(/ü/gu, 'v')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/gu, '')
    .replace(/[^a-zv]/gu, '');
}

export function generateChineseHintMetadata({ engineRoot = defaultEngineRoot, quiet = false } = {}) {
  const sourceDir = path.join(engineRoot, 'src');
  const seedWords = fs.readFileSync(path.join(sourceDir, 'zhAnswerWords.seed.txt'), 'utf8')
    .split(/\r?\n/u)
    .map((word) => word.trim())
    .filter(Boolean);
  const clues = JSON.parse(fs.readFileSync(path.join(sourceDir, 'zhHintClues.seed.json'), 'utf8'));
  const manifest = JSON.parse(fs.readFileSync(path.join(sourceDir, 'zhDictionary.generated.json'), 'utf8'));
  const entries = Object.assign({}, ...manifest.shards.map((id) => (
    JSON.parse(fs.readFileSync(path.join(sourceDir, 'zhDictionaryShards', `${id}.json`), 'utf8')).entries ?? {}
  )));

  const clueWords = Object.keys(clues);
  const seedSet = new Set(seedWords);
  const missing = seedWords.filter((word) => typeof clues[word] !== 'string');
  const extra = clueWords.filter((word) => !seedSet.has(word));
  if (missing.length || extra.length) {
    throw new Error(`Chinese hint clues diverge from the answer seed (missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'})`);
  }

  const metadata = {};
  for (const word of seedWords) {
    const entry = entries[word];
    if (!entry) throw new Error(`Chinese answer is missing dictionary metadata: ${word}`);
    const pronunciation = entry.pronunciations?.[0];
    if (!pronunciation?.pinyinMarked || !Array.isArray(pronunciation.tones) || pronunciation.tones.length !== 2) {
      throw new Error(`Chinese answer is missing a canonical two-syllable pronunciation: ${word}`);
    }
    if (!pronunciation.tones.every((tone) => Number.isInteger(tone) && tone >= 1 && tone <= 5)) {
      throw new Error(`Chinese answer has a malformed tone pattern: ${word}`);
    }
    const meaning = clues[word].trim();
    if (meaning.length < 12 || meaning.length > 120 || /\p{Script=Han}/u.test(meaning)) {
      throw new Error(`Chinese answer has an invalid broad-meaning clue: ${word}`);
    }
    const spokenKey = pinyinKey(pronunciation.pinyinMarked);
    if (spokenKey && pinyinKey(meaning).includes(spokenKey)) {
      throw new Error(`Chinese broad-meaning clue exposes canonical pinyin: ${word}`);
    }
    metadata[word] = {
      pinyinMarked: pronunciation.pinyinMarked,
      tones: pronunciation.tones,
      meaning,
      firstCharacter: Array.from(word)[0],
    };
  }

  const output = `// Generated by scripts/generate-zh-hints.mjs. Do not edit by hand.\n`
    + `export const ZH_HINT_METADATA = ${JSON.stringify(metadata, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(sourceDir, 'zhHintMetadata.generated.ts'), output);
  if (!quiet) process.stdout.write(`Generated Chinese hint metadata for ${seedWords.length} answers\n`);
  return metadata;
}

if (process.argv[1] && path.resolve(process.argv[1]) === modulePath) {
  generateChineseHintMetadata();
}
