export function translateSemanticCategory(value) {
  const korean = String(value ?? '').trim();
  if (!korean) return null;
  const parts = korean.split(/\s*>\s*/u).map((part) => part.trim()).filter(Boolean);
  const translations = parts.map((part) => CATEGORY_PART_TRANSLATIONS[part]);
  if (translations.some((part) => !part)) return null;
  return {
    korean: parts.join(' > '),
    english: translations.join(' > '),
  };
}
