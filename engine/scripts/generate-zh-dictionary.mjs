import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import AdmZip from 'adm-zip';
import { buildChineseSnapshots } from './cccedict-import-lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const engineRoot = path.resolve(__dirname, '..');
const sourcePath = process.argv[2] ? path.resolve(process.argv[2]) : null;
if (!sourcePath || !fs.existsSync(sourcePath)) {
  throw new Error('Pass an explicit CC-CEDICT v1 .txt, .gz, or .zip source path');
}

const sourceBytes = fs.readFileSync(sourcePath);
let sourceText;
if (sourcePath.endsWith('.gz')) {
  sourceText = zlib.gunzipSync(sourceBytes).toString('utf8');
} else if (sourcePath.endsWith('.zip')) {
  const archive = new AdmZip(sourceBytes);
  const entry = archive.getEntries().find((candidate) => !candidate.isDirectory && /(?:\.txt|\.u8)$/iu.test(candidate.entryName));
  if (!entry) throw new Error('CC-CEDICT ZIP does not contain a text dictionary');
  sourceText = entry.getData().toString('utf8');
} else {
  sourceText = sourceBytes.toString('utf8');
}

const answerWords = fs.readFileSync(path.join(engineRoot, 'src', 'zhAnswerWords.seed.txt'), 'utf8')
  .split(/\r?\n/u)
  .map((word) => word.trim())
  .filter(Boolean);
const sourceSha256 = crypto.createHash('sha256').update(sourceBytes).digest('hex');
const snapshots = buildChineseSnapshots(sourceText, answerWords, sourceSha256);

const json = (value) => `${JSON.stringify(value)}\n`;
const dictionaryShardCount = 64;
const dictionaryShardIds = Array.from({ length: dictionaryShardCount }, (_, index) => index.toString(16).padStart(2, '0'));
const dictionaryShards = Object.fromEntries(dictionaryShardIds.map((id) => [id, {}]));
for (const [word, entry] of Object.entries(snapshots.dictionary.entries)) {
  const first = Array.from(word)[0];
  const id = ((first?.codePointAt(0) ?? 0) % dictionaryShardCount).toString(16).padStart(2, '0');
  dictionaryShards[id][word] = entry;
}
const dictionaryShardDir = path.join(engineRoot, 'src', 'zhDictionaryShards');
fs.mkdirSync(dictionaryShardDir, { recursive: true });
for (const id of dictionaryShardIds) {
  fs.writeFileSync(path.join(dictionaryShardDir, `${id}.json`), json({ entries: dictionaryShards[id] }));
}
fs.writeFileSync(path.join(engineRoot, 'src', 'zhDictionary.generated.json'), json({
  metadata: snapshots.metadata,
  entryCount: snapshots.guessWords.length,
  shardCount: dictionaryShardCount,
  shards: dictionaryShardIds,
}));

const pinyinShardIds = [...'abcdefghijklmnopqrstuvwxyz', '_'];
const pinyinShards = Object.fromEntries(pinyinShardIds.map((id) => [id, {}]));
for (const [key, candidates] of Object.entries(snapshots.pinyinIndex.candidates)) {
  const id = /^[a-z]/u.test(key) ? key[0] : '_';
  pinyinShards[id][key] = candidates;
}
const pinyinShardDir = path.join(engineRoot, 'src', 'zhPinyinShards');
fs.mkdirSync(pinyinShardDir, { recursive: true });
for (const id of pinyinShardIds) {
  fs.writeFileSync(path.join(pinyinShardDir, `${id}.json`), json({ candidates: pinyinShards[id] }));
}
fs.writeFileSync(path.join(engineRoot, 'src', 'zhPinyinIndex.generated.json'), json({
  metadata: snapshots.metadata,
  keyCount: Object.keys(snapshots.pinyinIndex.candidates).length,
  shards: pinyinShardIds,
}));

const lexiconSource = `// Generated by scripts/generate-zh-dictionary.mjs. Do not edit by hand.\n`
  + `export const CHINESE_LEXICON_SOURCE = ${JSON.stringify(snapshots.metadata, null, 2)} as const;\n\n`
  + `export const ZH_ANSWER_WORDS: readonly string[] = ${JSON.stringify(snapshots.answerWords, null, 2)};\n\n`
  + `export const ZH_GUESS_WORDS_LIST: readonly string[] = ${JSON.stringify(snapshots.guessWords, null, 2)};\n`;
fs.writeFileSync(path.join(engineRoot, 'src', 'zhLexicon.generated.ts'), lexiconSource);

process.stdout.write(`Generated Chinese dictionary: ${snapshots.guessWords.length} accepted guesses, ${snapshots.answerWords.length} answers, ${Object.keys(snapshots.pinyinIndex.candidates).length} pinyin keys\n`);
